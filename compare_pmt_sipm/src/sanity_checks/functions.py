def get_gps_time_selected_dates():
    """
    Compute GPS times for a fixed set of selected dates.

    The selected dates are:
        - October 2015
        - January 2016
        - April 2016
        - July 2016
        - November 2016

    GPS time is defined as the number of seconds since 1980-01-06T00:00:00 UTC,
    as provided by `astropy.time.Time.gps`.

    Returns:
        numpy.ndarray:
            Array of GPS times (float64), one for each selected date.
    """

    gps_times = []
    selected_dates = ["2015-10", "2016-01", "2016-04", "2016-07", "2016-11"]

    # Define the date in UTC
    for dd in selected_dates:
        utc_time = Time(f"{dd}-01T00:00:00", scale="utc")

        # Convert to GPS time
        gps_time = utc_time.gps
        gps_times.append(gps_time)

    #print(f"years = {years}")
    #print(f"gps_times_january = {gps_times}")
    return np.array(gps_times)

def plot_time_series(df):
    """
    Plots time series of lg(E), rho35, and nr of events

    This function creates three time series plots:
    1. $\lg(E / \mathrm{eV})$ vs GPS time
    2. $\rho_{35}$ vs GPS time
    3. Number of events per 30-day bin vs GPS time

    The x-axis uses GPS time in gigaseconds, with secondary axes showing selected
    reference dates (Oct 2015, Jan 2016, Apr 2016, Jul 2016, Nov 2016).

    Args:
        df (pandas.DataFrame): DataFrame containing at least the following columns:
            - "gps_sec": GPS timestamp in seconds
            - "lgE": logarithm of the event energy
            - "rho450_cic": reconstructed $\rho_{35}$ value

    Returns:
        dict: A dictionary with entries:
            {
                "energy": {"fig": fig, "ax": ax},
                "rho35": {"fig": fig2, "ax": ax2},
                "nr_events": {"fig": fig3, "ax": ax3}
            }
    """

    gps_time_seconds = df["gps_sec"].to_numpy()
    # express gps time in Gs
    gps_time = gps_time_seconds / 10**9
    lge = df["lgE"].to_numpy()
    rho35 = df["rho450_cic"].to_numpy()

    # gps time [Gs] bin edges
    seconds_hour = 3600
    seconds_in_day = 24*seconds_hour
    step_gps_sec = 30*seconds_in_day
    step_gps = step_gps_sec / 10**9
    gps_bin_edges = list(np.arange(min(gps_time), max(gps_time),
                            step=step_gps))

    # time series of lgE
    plge = Profile(x=gps_time, y=lge).doProfile(bins=gps_bin_edges)
    
    # time series of rho35
    prho35 = Profile(x=gps_time, y=rho35)
    prho35.doProfile(bins=gps_bin_edges)

    # time series of number of events (# of events in each time bin)
    #n_events_per_bin = [len(dist) for dist in prho35.profileydistributions]
    n_events_per_bin = prho35.n_per_bin

    ### Ploting
    # plots parameters
    ms = 8

    # gps of selected dates for the secondary axis
    gps_selected_dates_sec = get_gps_time_selected_dates()
    # convert to Gs
    gps_selected_dates = gps_selected_dates_sec / 10**9

    # =============================
    ### Plot of energy time series
    fig, ax = plt.subplots(1, 1, figsize=(14, 8))

    ax.errorbar(plge.x_center, plge.y_mean,
            yerr=plge.y_std_of_mean,
           label="mean", ms=ms, fmt="^")
    ax.errorbar(plge.x_center, plge.y_median,
            yerr=plge.y_iql_std_of_mean,
            fmt="v", mfc="None",
           label="median")

    ax.set_xlim(left=min(np.array(gps_selected_dates)),
            right=max(np.array(gps_selected_dates)))

    ax.set_xticks(np.array(gps_selected_dates))

    # secondary axis with dates
    # Create a twin x-axis
    axdates1 = ax.twiny()

    # Adjust the second x-axis limits to match the first
    axdates1.set_xlim(ax.get_xlim())

    axdates1.set_xticks(np.array(gps_selected_dates))
    dates_labels = ["Oct 2015", "Jan 2016", "Apr 2016", "Jul 2016", "Nov 2016"]
    axdates1.set_xticklabels(dates_labels)

    ax.legend()

    ax.set_xlabel(r"GPS time / Gs")
    ax.set_ylabel(r"$\lg(E / \text{eV})$")


    # =============================
    ### Plot of rho35 time series
    fig2, ax2 = plt.subplots(1, 1, figsize=(14, 8))


    ax2.errorbar(prho35.x_center, prho35.y_mean,
            yerr=prho35.y_std_of_mean,
           label="mean", ms=ms, fmt="^")
    ax2.errorbar(prho35.x_center, prho35.y_median,
            yerr=prho35.y_iql_std_of_mean,
            fmt="v", mfc="None",
           label="median")

    ax2.set_xlim(left=min(np.array(gps_selected_dates)),
            right=max(np.array(gps_selected_dates)))

    ax2.set_xticks(np.array(gps_selected_dates))

    # secondary axis with dates
    # Create a twin x-axis
    axdates1_2 = ax2.twiny()

    # Adjust the second x-axis limits to match the first
    axdates1_2.set_xlim(ax2.get_xlim())

    axdates1_2.set_xticks(np.array(gps_selected_dates))
    dates_labels = ["Oct 2015", "Jan 2016", "Apr 2016", "Jul 2016", "Nov 2016"]
    axdates1_2.set_xticklabels(dates_labels)

    ax2.set_xlabel(r"GPS time / Gs")
    ax2.set_ylabel(r"$\rho_{35} \, / \, \text{m}^{-2}$")

    ax2.legend()

    # ==================================
    ### Plot of nr of events time series
    fig3, ax3 = plt.subplots(1, 1, figsize=(14, 8))


    ax3.errorbar(prho35.x_center, n_events_per_bin,
            yerr=np.sqrt(n_events_per_bin),
            ms=ms, fmt="^")

    ax3.set_xlim(left=min(np.array(gps_selected_dates)),
            right=max(np.array(gps_selected_dates)))

    ax3.set_xticks(np.array(gps_selected_dates))

    # secondary axis with dates
    # Create a twin x-axis
    axdates1_3 = ax3.twiny()

    # Adjust the second x-axis limits to match the first
    axdates1_3.set_xlim(ax3.get_xlim())

    axdates1_3.set_xticks(np.array(gps_selected_dates))
    dates_labels = ["Oct 2015", "Jan 2016", "Apr 2016", "Jul 2016", "Nov 2016"]
    axdates1_3.set_xticklabels(dates_labels)

    ax3.set_xlabel(r"GPS time / Gs")
    ax3.set_ylabel(r"nr of events")

    ### add vertical lines in the selected dates
    for gg in gps_selected_dates:
        ax.axvline(gg, ls="--", color="grey")
        ax2.axvline(gg, ls="--", color="grey")
        ax3.axvline(gg, ls="--", color="grey")

    return {"energy": {"fig": fig, "ax": ax},
            "rho35": {"fig": fig2, "ax": ax2},
            "nr_events": {"fig": fig3, "ax": ax3}}


def plot_energy_distribution(df, lge_min, lge_max):
    """
    
    """
    n = len(df)

    # energy distribution
    fig, ax = plt.subplots(1, 1, figsize=(14, 8))


    lge = df["lgE"].to_numpy()
    
    lge = lge[(lge_min < lge) & (lge < lge_max) ]

    nbins = 10

    bin_edges = np.linspace(lge_min, lge_max, nbins+1)
    bin_centers = bin_edges[:-1] + np.diff(bin_edges) / 2

    counts, _, __ = ax.hist(lge, histtype="step", lw=3, label=f"{n} events", bins=bin_edges)
    ax.errorbar(bin_centers, counts, yerr=np.sqrt(counts), fmt="o")
    ax.set_xlabel(r"$\lg (E / \text{eV})$")
    ax.set_yscale("log")
    ax.set_ylabel("Counts")
    ax.legend()

    # same but normalized to a pdf 
    fig2, ax2 = plt.subplots(1, 1, figsize=(14, 8))
    
    pdf, _, __= ax2.hist(lge, histtype="step", lw=3, label=f"{n} events", bins=bin_edges,
                         density=True)
     
    ax2.set_xlabel(r"$\lg (E / \text{eV})$")
    ax2.set_ylabel("pdf")
    ax2.legend()


    return {"hist": {"fig": fig, "ax": ax},
            "hist_norm": {"fig": fig2, "ax": ax2}}

