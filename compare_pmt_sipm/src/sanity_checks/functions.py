def make_cuts(df, lge_min, lge_max, theta_max, hottest_sd_in_uc):
    """
    Apply selection cuts to an event-level DataFrame.

    Args:
        df (pandas.DataFrame): DataFrame with event-level quantities,
            as produced by `adst_to_pickle.py` or loaded from the
            corresponding `.dat` file generated by `pickle_to_dat.py`.
        lge_min (float): Minimum log10(energy) threshold.
        lge_max (float): Minimum log10(energy) threshold.
        theta_max (float): Maximum zenith angle [deg].
        hottest_sd_in_uc (bool): If True, only events whose hottest
            surface detector (SD) station is within the unitary cell
            will be kept.

    Returns:
        pandas.DataFrame: A filtered DataFrame containing only the
        events that satisfy the given cuts. Index is reset.
    """
    # Sanity check: be sure that there is no duplication of events
    unique_events = np.unique(df["event_id"].to_numpy())
    assert len(df) == len(unique_events), f"{len(df)}, {len(unique_events)}"

    # Energy cut
    df = df.loc[(df["lgE"] > lge_min) & (df["lgE"] < lge_max)]

    # Zenith angle cut
    df = df.loc[df["theta"] < theta_max]

    # Hottest station cut (within the unitary cell)
    if hottest_sd_in_uc:
        # Includes special case: doublet station 93 -> station 710
        unitary_cell_ids = [93, 1764, 1570, 1622, 688, 1773, 1574, 710]
        df = df.loc[df["hottest_sd_station"].isin(unitary_cell_ids)]

    # Reset index before returning
    return df.reset_index(drop=True)


