def test_attenuation_function(df, f_att_expected="pmt_paper"):
    """
    Test if the attenuation function used to convert rho450 to rho35 matches the expected one.

    Args:
        df (pandas.DataFrame): Must contain columns:
            - "rho450": reference density at 450 m
            - "rho450_cic": corrected density (rho35)
            - "theta": zenith angle in degrees
        f_att_expected (str, optional): Identifier of the expected attenuation function.
            Currently only "pmt_paper" is supported. Default = "pmt_paper".

    Returns:
        dict: {"fig": matplotlib.Figure, "ax": np.ndarray of matplotlib.Axes}
    """

    if f_att_expected not in ["pmt_paper"]:
        raise ValueError("f_att_expected value not allowed")

    ## f_att as deduced from data
    fatt_data = df["rho450"].to_numpy() / df["rho450_cic"].to_numpy()

    theta = df["theta"].to_numpy()
    sin2theta = np.sin(np.deg2rad(theta))**2
    sin2_ref = np.sin(np.deg2rad(35))**2
    xsin = sin2theta - sin2_ref

    cos2theta = np.cos(np.deg2rad(theta))**2
    cos2_ref = np.cos(np.deg2rad(35))**2
    xcos = cos2theta - cos2_ref

    if f_att_expected == "pmt_paper":
        a_pmt = 0.54
        b_pmt = -1.02
        f_expected = 1 + a_pmt * xcos + b_pmt*xcos**2

        # although in the PMT paper it is parameterized as x = cos2theta -cos2_35,
        # the plot it is as a function of sin2theta

        theta_plot = np.linspace(0, 45, 300)
        sin2plot = np.sin(np.deg2rad(theta_plot))**2
        cos2plot = np.cos(np.deg2rad(theta_plot))**2
        xplot = cos2plot - np.cos(np.deg2rad(35))**2

        f_expected_plot = 1 + a_pmt*xplot + b_pmt*xplot**2

    fig, ax = plt.subplots(1, 2, figsize=(18, 7))

    # 1st, scatter plot vs function
    ax[0].errorbar(sin2theta, fatt_data, fmt="o", ms=3, alpha=0.5, mfc="None", label="data")

    ax[0].plot(sin2plot, f_expected_plot, "-", lw=2, label=f"expected {f_att_expected}")

    ax[0].axhline(y=1, ls="--", color="k")
    ax[0].axvline(x=np.sin(np.deg2rad(35))**2)
    ax[0].set_xlabel(r"$\sin ^2 \theta$")
    ax[0].set_ylabel(r"$\rho_{450} \, / \, \rho_{35} = f_\text{att}$")
    ax[0].legend()

    # 2nd, (f_data - f_expected) / f_expected -> this should be exactly zero

    difference = (fatt_data - f_expected) / f_expected
    stats = (f"mean = {np.mean(difference)}\n"
             f"median = {np.median(difference)}\n"
             f"std = {np.std(difference, ddof=1)}\n")

    ax[1].hist(difference, histtype="step", lw=2, label=f"{stats}")
    ax[1].set_xlabel(r"$(f_\text{att}^\text{data} - f_\text{att}^\text{expected}) \, / \, f_\text{att}^\text{expected})$")
    ax[1].legend()

    return {"fig": fig, "ax": ax}

def test_beta_parameterization(df):
    """
    Test if the beta (slope) parameterization of the LDF correctly matches the expected one.

    Args:
        df (pandas.DataFrame): Must contain columns:
            - "beta": reference density at 450 m
            - "energy"
            - "theta": zenith angle in degrees


    Returns:
        dict: {"fig": matplotlib.Figure, "ax": np.ndarray of matplotlib.Axes}
    """

    lge = df["lgE"].to_numpy()
    beta = df["beta"].to_numpy()
    theta = df["theta"].to_numpy()

    sec_theta = 1 / np.cos(np.deg2rad(theta))

    ### PMT paper beta parameterization
    a0, a1 = 4.4, -1.1
    sec_plot = np.linspace(1, 1/np.cos(np.deg2rad(45)), 300)
    beta_pmt_expected = a0 + a1*sec_plot

    fig, ax = plt.subplots(1, 1, figsize=(14, 7))

    # 1st, scatter plot vs function
    ax.errorbar(sec_theta, beta, fmt="o", ms=3, alpha=0.5, mfc="None", label="data")

    ax.plot(sec_plot, beta_pmt_expected, "-", lw=3, label="expected PMT paper")


    ax.set_xlabel(r"$\sec \theta$")
    ax.set_ylabel(r"$\beta$")
    ax.legend()

    return {"fig": fig, "ax": ax}

